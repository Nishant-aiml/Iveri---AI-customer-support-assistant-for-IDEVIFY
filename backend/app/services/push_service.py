import os
import json
import logging
import base64
import asyncio
from typing import Any
from cryptography.hazmat.primitives import serialization
from py_vapid import Vapid

logger = logging.getLogger("idevify-push")

class PushService:
    def __init__(self):
        self.vapid_claim_email = os.getenv("VAPID_CLAIM_EMAIL", "mailto:alerts@idevify.com")
        self._private_key_file = os.getenv(
            "VAPID_PRIVATE_KEY_FILE",
            os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "vapid_private_key.pem"))
        )
        self.vapid_public_key: str = os.getenv("VAPID_PUBLIC_KEY", "")
        self.vapid_private_key: str = os.getenv("VAPID_PRIVATE_KEY", "")
        self._init_vapid_keys()

    def _init_vapid_keys(self) -> None:
        """Initializes or auto-generates a persistent P-256 VAPID keypair for Web Push RFC 8292."""
        try:
            # Case 1: Private key file already exists or can be generated by py_vapid
            if os.path.exists(self._private_key_file):
                vapid = Vapid.from_file(self._private_key_file)
            elif self.vapid_private_key and "-----BEGIN" in self.vapid_private_key:
                vapid = Vapid.from_pem(self.vapid_private_key.encode("utf-8"))
            elif self.vapid_private_key and os.path.isfile(self.vapid_private_key):
                self._private_key_file = self.vapid_private_key
                vapid = Vapid.from_file(self._private_key_file)
            else:
                logger.info("Generating persistent P-256 VAPID keypair for background mobile push notifications...")
                os.makedirs(os.path.dirname(self._private_key_file), exist_ok=True)
                vapid = Vapid.from_file(self._private_key_file)

            # Derive the uncompressed base64url public key (87 chars) required by browser PushManager
            raw_pub = vapid.public_key.public_bytes(
                serialization.Encoding.X962,
                serialization.PublicFormat.UncompressedPoint
            )
            derived_pub_b64 = base64.urlsafe_b64encode(raw_pub).decode().rstrip("=")

            if not self.vapid_public_key:
                self.vapid_public_key = derived_pub_b64

            logger.info("VAPID keypair initialized successfully for real-time mobile push notifications.")
        except Exception as e:
            logger.error(f"Failed to initialize VAPID keys: {e}")

    def get_public_key(self) -> str:
        """Returns the base64url-encoded VAPID public key for browser push registration."""
        return self.vapid_public_key

    def _get_private_key_ref(self) -> Any:
        """Returns the private key argument for pywebpush (either file path or PEM string)."""
        if os.path.exists(self._private_key_file):
            return self._private_key_file
        if self.vapid_private_key:
            return self.vapid_private_key
        return self._private_key_file

    async def send_web_push(self, subscription: dict[str, Any], payload: dict[str, Any]) -> bool:
        """
        Dispatches an RFC 8292 Web Push notification to a subscribed mobile/desktop browser client.
        Uses 24-hour delivery TTL so closed phones receive the alert the instant they check in.
        """
        endpoint = subscription.get("endpoint", "")
        if not endpoint:
            return False

        try:
            from pywebpush import webpush, WebPushException

            priv_key_ref = self._get_private_key_ref()
            claims = {"sub": self.vapid_claim_email}
            payload_str = json.dumps(payload)

            loop = asyncio.get_running_loop()
            await loop.run_in_executor(
                None,
                lambda: webpush(
                    subscription_info=subscription,
                    data=payload_str,
                    vapid_private_key=priv_key_ref,
                    vapid_claims=claims,
                    ttl=86400  # 24 hours delivery TTL for closed/sleeping phones
                )
            )
            logger.info(f"Dispatched Web Push notification to {endpoint[:35]}... Title: {payload.get('title')}")
            return True
        except Exception as e:
            from pywebpush import WebPushException
            if isinstance(e, WebPushException) and e.response is not None and e.response.status_code in (404, 410):
                logger.info(f"Subscription expired ({e.response.status_code}), removing endpoint: {endpoint[:35]}...")
                asyncio.create_task(self.remove_expired_subscription(endpoint))
            else:
                logger.warning(f"Web Push dispatch notice: {e}")
            return False

    async def remove_expired_subscription(self, endpoint: str) -> None:
        """Cleans up expired or uninstalled browser push subscriptions."""
        try:
            from app.database import AsyncSessionLocal
            from app.models.push_subscription import PushSubscription
            from sqlalchemy import delete

            async with AsyncSessionLocal() as db:
                await db.execute(delete(PushSubscription).where(PushSubscription.endpoint == endpoint))
                await db.commit()
                logger.info(f"Removed expired push subscription from DB: {endpoint[:40]}...")
        except Exception as db_err:
            logger.warning(f"Error removing expired push subscription: {db_err}")

push_service = PushService()
